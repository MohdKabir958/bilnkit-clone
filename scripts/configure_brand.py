#!/usr/bin/env python3
"""Generate shared brand constants without renaming internal APIs or database fields."""
import argparse
import json
from pathlib import Path
import re
import sys
from xml.sax.saxutils import escape

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
brand = json.loads((root / 'branding/brand.json').read_text())
for key in ('name', 'customerName', 'vendorName', 'driverName'):
    if not isinstance(brand[key], str) or not re.fullmatch(r'[A-Za-z0-9 .&-]{1,60}', brand[key]):
        raise SystemExit(f'Invalid {key}: use 1-60 simple display-name characters.')
for key in ('primary', 'accent'):
    if not re.fullmatch(r'#[0-9a-fA-F]{6}', brand[key]):
        raise SystemExit(f'Invalid {key}: use #RRGGBB.')
for role, identity in brand['applicationIds'].items():
    if not re.fullmatch(r'[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*){2,}', identity):
        raise SystemExit(f'Invalid Android application ID for {role}.')
if brand['logoAsset'] and not re.fullmatch(r'assets/brand/[A-Za-z0-9_.-]+', brand['logoAsset']):
    raise SystemExit('logoAsset must refer to a file in the shared package assets/brand/.')

json_text = json.dumps(brand, indent=2)
generated = {
    'backend/src/config/brand.ts': '// Generated by scripts/configure_brand.py.\nexport const brand = ' + json_text + ' as const;\n',
    'web/super_admin/src/config/brand.ts': '// Generated by scripts/configure_brand.py.\nexport const brand = ' + json_text + ' as const;\n',
    'packages/kraveo_ui/lib/src/brand_config.dart': '// Generated by scripts/configure_brand.py.\nclass BrandConfig {\n  BrandConfig._();\n' + ''.join(
        f'  static const {key} = {json.dumps(brand[key])};\n' for key in ('name', 'customerName', 'vendorName', 'driverName', 'logoAsset', 'supportEmail')) +
        f'  static const primary = 0xFF{brand["primary"][1:]};\n  static const accent = 0xFF{brand["accent"][1:]};\n}}\n',
    'branding/android.properties': '# Generated by scripts/configure_brand.py.\n' + ''.join(
        f'{role}.applicationId={brand["applicationIds"][role]}\n{role}.label={brand[key]}\n'
        for role, key in [('customer', 'customerName'), ('vendor', 'vendorName'), ('driver', 'driverName')]),
}
for role, key in [('customer', 'customerName'), ('vendor', 'vendorName'), ('driver', 'driverName')]:
    generated[f'apps/{role}_app/android/app/src/main/res/values/branding.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/configure_brand.py. -->\n'
        f'<resources><string name="app_name">{escape(brand[key])}</string></resources>\n')
    generated[f'apps/{role}_app/android/app/src/main/res/drawable/market_launcher.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">'
        '<item android:drawable="@mipmap/ic_launcher"/></layer-list>\n')
    splash = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '  <item android:drawable="@android:color/white"/>\n'
        '  <item android:gravity="center" android:width="240dp" android:height="144dp" android:drawable="@drawable/brand_logo"/>\n'
        '</layer-list>\n')
    for qualifier in ('drawable', 'drawable-v21'):
        generated[f'apps/{role}_app/android/app/src/main/res/{qualifier}/launch_background.xml'] = splash
    modern_splash = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<resources>\n  <style name="LaunchTheme" parent="@android:style/Theme.Light.NoTitleBar">\n'
        '    <item name="android:windowSplashScreenBackground">@android:color/white</item>\n'
        '    <item name="android:windowSplashScreenAnimatedIcon">@drawable/brand_splash_icon</item>\n'
        '    <item name="android:windowBackground">@drawable/launch_background</item>\n'
        '  </style>\n</resources>\n')
    for qualifier in ('values-v31', 'values-night-v31'):
        generated[f'apps/{role}_app/android/app/src/main/res/{qualifier}/styles.xml'] = modern_splash
    color_name = 'kraveo_notification_color' if role == 'customer' else 'kraveo_notification_accent'
    generated[f'apps/{role}_app/android/app/src/main/res/values/colors.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<resources><color name="{color_name}">{brand["primary"]}</color></resources>\n')
stale = []
for name, contents in generated.items():
    dest = root / name
    if args.check:
        if not dest.exists() or dest.read_text() != contents:
            stale.append(name)
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(contents)
if stale:
    print('Run python3 scripts/configure_brand.py; stale files: ' + ', '.join(stale), file=sys.stderr)
    sys.exit(1)
print('Brand configuration is current.' if args.check else 'Brand configuration generated.')
